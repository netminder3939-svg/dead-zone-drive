// Phone top bar, pick Cancel, GPS chip units, and a far-front clan spawn. Local page only.
const { chromium, devices } = require('playwright');
require('./bindlog').bind('phone-front');
let failed = 0;
const ok = (n, c, e) => { if (!c) failed++; console.log((c ? 'PASS ' : 'FAIL ') + n + (e != null ? ' ' + JSON.stringify(e) : '')); };
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices['iPhone 13'], geolocation: { latitude: 47.7796, longitude: -116.8923, accuracy: 8 }, permissions: ['geolocation'] });
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', e => errs.push(e.message));
  await p.goto('http://127.0.0.1:8767/?local', { waitUntil: 'load' });
  await p.fill('#obName', 'Ada');
  await p.fill('#obTeam', 'qacrew');
  await p.click('#obGo');
  await p.waitForFunction(() => /GPS|Finding/.test((document.getElementById('gpschip') || {}).textContent || ''), null, { timeout: 20000 });
  const ui = await p.evaluate(() => {
    const gate = document.getElementById('auth12'); if (gate) gate.remove();
    G.playLocked = false;
    for (const k of Object.keys(RES)) P.res[k] = 48500;
    UI.hud(); layout15();
    const hud = document.getElementById('hud').getBoundingClientRect();
    const res = document.getElementById('res').getBoundingClientRect();
    const mode = document.getElementById('mode').getBoundingClientRect();
    const id = hexAt(47.7796, -116.8923).id;
    claimTile(id);
    W().sh = { hex: id, hpPct: 1, state: 'up', buildEnd: 0, everBuilt: true };
    P.stronghold = { level: 1 }; P.startSh26 = 1; P.startShMoved26 = 1; P.name = P.name || 'Ada';
    G.op15open = 0; bar15(true);
    const closed = document.querySelectorAll('#op15 button').length;
    const chip = document.getElementById('gpschip');
    chip.textContent = '📡 GPS ±12m';
    fixMiles15();
    const near = chip.textContent;
    chip.textContent = '📡 GPS ±2000m';
    fixMiles15();
    const far = chip.textContent;
    toast('This is a long message that used to run off both sides of a phone screen and must wrap inside the viewport.');
    const toastBox = [...document.querySelectorAll('#toast div')].map(d => { const r = d.getBoundingClientRect(); return { left: r.left, right: r.right, w: innerWidth }; });
    const out = document.createElement('button'); out.id = 'a12out'; out.className = 'chip'; out.textContent = 'Log out'; document.getElementById('hud').appendChild(out);
    const logout = getComputedStyle(out).fontSize;
    return { resBelow: res.top >= hud.top + 20, modeBelow: mode.top >= hud.bottom - 1, closed, near, far, toastBox, logout, width: innerWidth };
  });
  ok('phone resources sit on their own row under the top bar', ui.resBelow && ui.modeBelow && ui.width <= 600, ui);
  ok('a tight GPS reading is in feet and a long one is in miles', /ft/.test(ui.near) && /mi/.test(ui.far) && !/km\b/.test(ui.near + ui.far), ui);
  ok('a long toast stays inside the phone width', ui.toastBox.length > 0 && ui.toastBox.every(d => d.left >= -1 && d.right <= d.w + 1), ui.toastBox);
  ok('the phone logout control is the icon, with the words removed from the layout', ui.logout === '0px', ui);
  ok('the base switcher starts as one button', ui.closed === 1, ui);
  await p.click('#op15 button');
  const opened = await p.evaluate(() => document.querySelectorAll('#op15 button').length);
  ok('opening the base switcher shows the list', opened > 1, opened);
  await p.evaluate(() => pick15('fwd'));
  await p.waitForSelector('#pick15 button', { state: 'visible' });
  const pickText = await p.locator('#pick15').innerText();
  await p.click('#pick15 button');
  const cancelled = await p.evaluate(() => ({ pick: G.pick15, bar: !!document.getElementById('pick15') }));
  ok('map picking shows a Cancel bar and Cancel clears it', /Tap the hex|Forward|teammate/.test(pickText) && /Cancel/.test(pickText) && cancelled.pick == null && !cancelled.bar, { pickText, cancelled });
  const spawn = await p.evaluate(() => {
    const home = hexAt(47.7796, -116.8923).id;
    const far = hexAt(38.10, -97.33).id;
    W(); const fx = FX();
    fx.start = Date.now(); fx.anchor = home; fx.f = fx.f || {}; fx.fronts15 = {};
    const step = HB().stepMin * 60e3;
    const since = Math.floor(Date.now() / step) * step;
    fx.fronts15[far] = { anchor: far, since, label: 'far front', takes: {} };
    registerDefs15();
    const k = Math.round(since / step);
    const t = k * HB().stepMin * 60e3;
    const ev = { grew: {}, took: [], held: [], fights: [], outposts: [], back: [], destroyed: [] };
    hordeStep(k, ev);
    const onTime = Object.keys(fx.f).filter(id => id.endsWith('~' + far));
    fx.f = {};
    const since2 = t + 500;
    fx.fronts15 = {};
    fx.fronts15[far] = { anchor: far, since: since2, label: 'far front', takes: {} };
    registerDefs15();
    hordeStep(k, ev);
    const early = Object.keys(fx.f).filter(id => id.endsWith('~' + far));
    return { stepMin: HB().stepMin, gap: since - t, onTime, early, slack: /since-1000/.test(String(hordeStep)) };
  });
  ok('a new regional front spawns its clans on the rounded step', spawn.onTime.length === 3 && spawn.early.length === 3 && spawn.slack, spawn);
  ok('no page errors', errs.length === 0, errs.slice(0, 3));
  console.log(failed ? 'FAILED ' + failed : 'ALL PASS');
  await b.close();
  process.exit(failed ? 1 : 0);
})().catch(e => { console.error('HARNESS', e); process.exit(1); });
